"""Канал, за подписку на который дают разовый бонус.

Здесь только разбор ссылки. Проверять подписку умеет адаптер мессенджера
(порт ``app/ports/channel.py``): ядро про getChatMember не знает.

Отдельная переменная окружения с именем канала не заводится намеренно. Имя
однозначно выводится из ссылки, а две переменные про одно и то же — это два
способа разойтись с действительностью: ссылку поменяли, имя забыли, и бот
проверяет подписку не на тот канал, показывая кнопку на новый.
"""

from __future__ import annotations

#: Где живут публичные каналы Telegram. Приватные приглашения (t.me/+код)
#: сюда не годятся: у них нет публичного имени, а проверять подписку нам не
#: по чему.
_TELEGRAM_HOSTS = ("https://t.me/", "http://t.me/", "t.me/")


def channel_username(url: str) -> str:
    """«@имя» канала из ссылки. Пусто — если это не публичный канал Telegram.

    Пустая строка не ошибка: она означает «предложения нет». Бонус за канал —
    вещь необязательная, и опечатка в ссылке не должна ронять бота целиком;
    она должна выключить одну кнопку и оставить след в логе.
    """
    cleaned = url.strip()
    for host in _TELEGRAM_HOSTS:
        if cleaned.startswith(host):
            name = cleaned.removeprefix(host).strip("/")
            break
    else:
        return ""
    # Отбрасываем всё, что после имени: параметры и якоря в ссылке на канал
    # встречаются, а частью имени не являются.
    name = name.split("?")[0].split("#")[0].split("/")[0]
    if not name or not _is_public_name(name):
        return ""
    return f"@{name}"


def _is_public_name(name: str) -> bool:
    """Похоже ли это на публичное имя канала.

    Плюс в начале — приглашение в приватный канал: имени у него нет, и
    подписку по нему не проверить.
    """
    return name[0].isalpha() and all(ch.isalnum() or ch == "_" for ch in name)
