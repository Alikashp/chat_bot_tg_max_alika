"""Почта покупателя — единственное, куда может прийти фискальный чек.

Спрашивается она не для рассылок и не для профиля: по 54-ФЗ чек надо
доставить, а из всего, что мы знаем о человеке, доставить чек можно только на
почту. В MAX номера телефона нам не даёт ни один экран, в Telegram он есть
только через отдельную кнопку постоянной клавиатуры, которой у нас нет.
Значит, адрес человек пишет сам, а мы обязаны его хотя бы бегло проверить:
опечатка в адресе — это недоставленный чек, а за него штраф.

Проверка здесь намеренно скупая. Полностью проверить адрес нельзя ничем,
кроме письма на него, а всякая «умная» регулярка отвергает чей-нибудь
настоящий адрес — и человек остаётся без подписки на ровном месте. Поэтому
отсекаем только то, что заведомо не адрес.
"""

from __future__ import annotations

import re

#: Потолок длины. 254 — предел адреса по RFC 5321, дальше начинается мусор.
MAX_EMAIL_LENGTH = 254

#: Что-то до собаки, что-то после, точка в домене и хотя бы две буквы в конце.
#: Пробелов нет нигде — их отсутствие и есть главная проверка.
_SHAPE = re.compile(r"^[^@\s]+@[^@\s.]+(\.[^@\s.]+)+$")


def normalise_email(reported: str) -> str | None:
    """Приводит написанное человеком к тому, что уедет в чек.

    None — написанное не похоже на адрес. Регистр домена и лишние пробелы по
    краям человеку прощаем: он пишет с телефона, где заглавная буква в начале
    подставляется сама.
    """
    cleaned = reported.strip().strip("<>").lower()
    if not cleaned or len(cleaned) > MAX_EMAIL_LENGTH:
        return None
    if _SHAPE.match(cleaned) is None:
        return None
    return cleaned
