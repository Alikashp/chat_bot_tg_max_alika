"""Имя пользователя в мессенджере — то, по чему его находит поддержка.

Человеку оно нигде не показывается: это не фича интерфейса, а строчка в базе,
которую читает живой человек, когда разбирает обращение. Поэтому здесь ровно
одно правило, и всё остальное следует из него:

    записанное имя должно быть сегодняшним, а не тем, что было при регистрации.

Имя в мессенджере меняют когда захотят, и записанное однажды через месяц
указывает не на того. Протухшее имя хуже отсутствующего: по нему поддержка
пойдёт искать и найдёт постороннего — с чужой перепиской и чужими платежами.

Отсюда и место вызова: не онбординг, а каждое обращение. Запись при этом
происходит только когда имя правда изменилось, так что в обычной жизни это
сравнение двух строк и ни одного запроса.
"""

from __future__ import annotations

from dataclasses import replace

from app.core.models import User, username_or_none
from app.core.scenarios.deps import Deps


async def remember_username(deps: Deps, user: User, reported: str | None) -> User:
    """Обновляет имя, если мессенджер назвал новое. Возвращает актуального.

    ``reported`` со значением None означает «имени нет», и записывается это
    так же честно, как и новое имя. Оба мессенджера присылают пользователя
    целиком при каждом обращении, поэтому пустое поле здесь — не молчание, а
    ответ: человек снял себе имя. Сохранить в этом случае прежнее значило бы
    оставить в базе имя, которого у него больше нет, — а по нему поддержка
    пойдёт искать и найдёт постороннего.
    """
    fresh = username_or_none(reported)
    if fresh == user.username:
        return user

    await deps.storage.set_username(user.id, fresh)
    deps.logger.info("username_changed", user_id=int(user.id))
    return replace(user, username=fresh)
