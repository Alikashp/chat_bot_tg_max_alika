"""Продуктовые настройки ядра.

Обычный frozen-dataclass, а не pydantic-settings: ядро не читает окружение
и вообще ничего не знает про то, откуда берутся значения. Их собирает
app/main.py и передаёт внутрь. Благодаря этому сценарии тестируются с любыми
числами, не трогая переменные окружения.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.core import referral


@dataclass(frozen=True, slots=True)
class CoreSettings:
    """Всё, что продуктовым сценариям нужно знать снаружи."""

    #: Имя бота без «собаки». Нужно для реферальных ссылок и подписи к картинке.
    bot_username: str

    #: Где живёт бот: t.me для Telegram, max.ru для MAX. Каждый адаптер
    #: получает свои настройки, поэтому ссылка всегда ведёт в тот мессенджер,
    #: из которого пришёл человек.
    referral_link_host: str = referral.TELEGRAM_HOST

    #: Часовой пояс, по которому наступает «завтра» из текста пейволла.
    #: Аудитория русскоязычная, поэтому сутки считаем по Москве.
    timezone: str = "Europe/Moscow"

    #: Модели по классам. Пользователю не показываются и им не выбираются
    #: (§2.2): Free и Лайт получают эконом-модель, Про и Макс — стандартную.
    model_economy: str = "gpt-5-mini"
    model_standard: str = "gpt-5"

    #: Сколько реплик диалога держим в контексте. Ограничение нужно, потому
    #: что счёт провайдера растёт вместе с длиной контекста, а полезность
    #: очень старых реплик — нет. Задаётся переменной DIALOG_MAX_TURNS.
    dialog_max_turns: int = 10

    #: С какого по счёту сообщения в диалоге показывается «🔄 Новый диалог».
    #: Ровно с десятого (§2.2): раньше кнопка только мешает.
    new_dialog_after_messages: int = 10

    #: Дневная норма картинок на бесплатном тарифе.
    free_daily_images: int = 3

    #: То же для пришедших по deeplink из бота презентаций (§2.1).
    presentation_daily_images: int = 5

    #: Награда за приглашённого друга — обоим (§2.7).
    referral_bonus_messages: int = 50
    referral_bonus_images: int = 5

    #: Потолок наград в сутки на одного пригласившего (антифрод, §2.7).
    referral_daily_reward_limit: int = 20

    #: Во сколько раз дороже оплата звёздами Telegram (§2.8: на 40% выше).
    stars_markup: float = 1.4

    #: Сколько рублей стоит одна звезда. Величина внешняя и меняется, поэтому
    #: приходит из окружения, а не зашита в код.
    rub_per_star: float = 1.6

    #: На сколько дней выдаётся подписка после оплаты.
    subscription_days: int = 30

    #: Потолок размера присланного фото (§3.5). Всё, что больше, отклоняется
    #: до обращения к провайдеру: пять мегабайт с запасом покрывают снимок
    #: с телефона, а платить за разбор чего-то большего незачем.
    max_photo_bytes: int = 5 * 1024 * 1024

    def __post_init__(self) -> None:
        if not self.bot_username:
            raise ValueError("bot_username обязателен: без него не собрать ссылку")
        if self.new_dialog_after_messages < 1:
            raise ValueError("new_dialog_after_messages должен быть не меньше 1")
        if self.dialog_max_turns < 2:
            raise ValueError("в контексте должно помещаться хотя бы два хода")
