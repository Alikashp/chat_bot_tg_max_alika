"""Продуктовые настройки ядра.

Обычный frozen-dataclass, а не pydantic-settings: ядро не читает окружение
и вообще ничего не знает про то, откуда берутся значения. Их собирает
app/main.py и передаёт внутрь. Благодаря этому сценарии тестируются с любыми
числами, не трогая переменные окружения.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.core import referral
from app.core.receipts import FiscalSettings


@dataclass(frozen=True, slots=True)
class CoreSettings:
    """Всё, что продуктовым сценариям нужно знать снаружи."""

    #: Имя бота без «собаки». Нужно для реферальных ссылок и подписи к картинке.
    bot_username: str

    #: Где живёт бот: t.me для Telegram, max.ru для MAX. Каждый адаптер
    #: получает свои настройки, поэтому ссылка всегда ведёт в тот мессенджер,
    #: из которого пришёл человек.
    referral_link_host: str = referral.TELEGRAM_HOST

    #: Показывать ли человеку его номер в профиле.
    #:
    #: Нужен для поддержки: по номеру находится запись в базе. В Telegram он
    #: лишний — там человека видно по @username, — а в MAX username есть не у
    #: всех, и без номера опознать написавшего нечем.
    show_user_number: bool = False

    #: Часовой пояс, по которому наступает «завтра» из текста пейволла.
    #: Аудитория русскоязычная, поэтому сутки считаем по Москве.
    timezone: str = "Europe/Moscow"

    #: Модели по классам. Пользователю не показываются и им не выбираются
    #: (§2.2): Free и Лайт получают эконом-модель, Про и Макс — стандартную.
    model_economy: str = "gpt-5-mini"
    model_standard: str = "gpt-5"

    #: Сколько реплик диалога держим в контексте. Ограничение нужно, потому
    #: что счёт провайдера растёт вместе с длиной контекста, а полезность
    #: очень старых реплик — нет. Задаётся переменной DIALOG_MAX_TURNS.
    dialog_max_turns: int = 10

    #: С какого по счёту сообщения в диалоге показывается «🔄 Новый диалог».
    #: Ровно с десятого (§2.2): раньше кнопка только мешает.
    new_dialog_after_messages: int = 10

    #: Дневная норма картинок на бесплатном тарифе.
    free_daily_images: int = 3

    #: То же для пришедших по deeplink из бота презентаций (§2.1).
    presentation_daily_images: int = 5

    #: Награда за приглашённого друга — обоим (§2.7).
    referral_bonus_messages: int = 50
    referral_bonus_images: int = 5

    #: Потолок наград в сутки на одного пригласившего (антифрод, §2.7).
    referral_daily_reward_limit: int = 20

    #: Во сколько раз дороже оплата звёздами Telegram (§2.8: на 40% выше).
    stars_markup: float = 1.4

    #: Сколько рублей стоит одна звезда. Величина внешняя и меняется, поэтому
    #: приходит из окружения, а не зашита в код.
    rub_per_star: float = 1.6

    #: На сколько дней выдаётся подписка после оплаты.
    subscription_days: int = 30

    #: За сколько часов предупреждаем о списании (§4.13 оферты: не позднее
    #: чем за 24 часа).
    reminder_hours: int = 24

    #: За сколько дней предупреждаем о новой цене (§4.17 оферты: не позднее
    #: чем за 7 дней).
    price_notice_days: int = 7

    #: Сколько дней повторяем неудавшееся списание, прежде чем прекратить
    #: подписку (§4.16 оферты: в течение 3 дней).
    charge_retry_days: int = 3

    #: Через сколько часов повторяем неудавшееся списание.
    charge_retry_hours: int = 24

    #: Сколько ждём списания, которое делает сам мессенджер.
    #:
    #: У звёздной подписки списывает Telegram, и о результате мы узнаём
    #: только когда он о нём сообщит. Сутки запаса нужны, чтобы задержка
    #: доставки не выглядела как отменённая подписка.
    stars_grace_hours: int = 24

    #: Где опубликованы оферта и политика обработки данных.
    #:
    #: Пустые означают, что документов нет, и тогда оплата не показывается
    #: вовсе. Брать деньги, не показав условия, нельзя — ни юридически, ни
    #: по-человечески.
    offer_url: str = ""
    privacy_url: str = ""

    #: Редакция документов. Записывается в заказ и в лог как доказательство
    #: того, с чем именно человек согласился.
    docs_version: str = ""

    #: Как платёж подпишется в банковской выписке — например «YM*ChatAIBot».
    #:
    #: Показывается на экране заказа до оплаты. Через месяц человек увидит эту
    #: строку в приложении банка, и если она ему незнакома — позвонит
    #: оспаривать списание. Показанная заранее, она этот звонок предотвращает.
    #: Задаётся провайдером, поэтому приходит из окружения, а не зашита в код.
    bank_statement_name: str = ""

    #: Фискальные параметры чека (54-ФЗ). None — чеки через ЮKassa не
    #: формируются: их выставляет онлайн-касса без нашего участия или
    #: продавец работает по режиму, где чеки идут мимо нас вовсе.
    #:
    #: Значения сюда приходят из окружения, потому что называет их бухгалтер
    #: по системе налогообложения, а не программист по своему разумению.
    #: Неверная ставка НДС — это неверный фискальный документ, а не опечатка.
    fiscal: FiscalSettings | None = None

    @property
    def receipts_ready(self) -> bool:
        """Отправляем ли мы чек вместе с платежом."""
        return self.fiscal is not None

    @property
    def documents_ready(self) -> bool:
        """Можно ли показывать оплату: документы опубликованы и версия задана."""
        return bool(self.offer_url and self.privacy_url and self.docs_version)

    #: Потолок размера присланного фото (§3.5). Всё, что больше, отклоняется
    #: до обращения к провайдеру: пять мегабайт с запасом покрывают снимок
    #: с телефона, а платить за разбор чего-то большего незачем.
    max_photo_bytes: int = 5 * 1024 * 1024

    def __post_init__(self) -> None:
        if not self.bot_username:
            raise ValueError("bot_username обязателен: без него не собрать ссылку")
        if self.new_dialog_after_messages < 1:
            raise ValueError("new_dialog_after_messages должен быть не меньше 1")
        if self.dialog_max_turns < 2:
            raise ValueError("в контексте должно помещаться хотя бы два хода")
