"""Откуда человек пришёл в бот.

Записывается один раз, при регистрации, и больше не меняется: источник
отвечает на вопрос «откуда он взялся», а не «где он был в последний раз».
Перезапись превратила бы его в бесполезное «последний deeplink», по которому
нельзя посчитать ни одну кампанию.

Значение — это payload из ссылки `?start=...` как есть: `ppt_result`,
`ref_XXXXXXXX`, `catalog`. Пустой payload означает, что человек нашёл бота
сам, и такой случай называется словом, а не пустой ячейкой: пустая ячейка
одинаково читается и как «пришёл сам», и как «мы не записали».
"""

from __future__ import annotations

#: Человек открыл бота без ссылки — нашёл поиском, по имени, из переписки.
DIRECT = "direct"

#: Потолок длины. Telegram больше 64 символов в payload и не пропускает, но
#: payload приходит снаружи и сочиняет его кто угодно: в базу должно попасть
#: ограниченное значение, а не всё, что прислали.
MAX_LENGTH = 64


def source_of(payload: str) -> str:
    """Источник регистрации из deeplink-payload.

    Управляющие символы вырезаются: payload приходит из внешнего мира, а
    колонку потом читает человек глазами и выгружает в таблицу, где перевод
    строки посреди значения ломает разбор.
    """
    cleaned = "".join(char for char in payload.strip() if char.isprintable())[
        :MAX_LENGTH
    ]
    return cleaned or DIRECT
