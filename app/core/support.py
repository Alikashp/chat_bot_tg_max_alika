"""Номер пользователя для поддержки.

Показывается человеку в профиле, по нему поддержка находит запись. Отдельная
величина, а не внутренний идентификатор строки: тот идёт по порядку, и по
нему видно, сколько всего людей в сервисе. Такие числа наружу не отдают.

И не реферальный код: код полуоткрытый — он лежит в ссылке, которую человек
рассылает друзьям. По чужому коду можно было бы выдать себя за другого.

Шесть цифр, а не буквы: номер диктуют в переписке и переписывают руками, а
цифры не путаются между раскладками и регистром.
"""

from __future__ import annotations

import secrets

#: Диапазон номеров. Начинаем с 100000, чтобы номер всегда был шестизначным:
#: «007431» человек напишет как «7431», и поиск не сработает.
FIRST_NUMBER = 100_000
LAST_NUMBER = 999_999


def generate_number() -> int:
    """Новый номер. Случайный, поэтому по нему ничего не пересчитать."""
    return secrets.randbelow(LAST_NUMBER - FIRST_NUMBER + 1) + FIRST_NUMBER
