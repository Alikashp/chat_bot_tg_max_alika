"""Порты провайдеров ИИ.

Ядро не знает ни имени провайдера, ни названия модели: модель приходит
параметром из конфига (§2.2 задания — модель не выбирается пользователем и
нигде не упоминается).
"""

from __future__ import annotations

from collections.abc import Sequence
from enum import StrEnum
from typing import Protocol

from app.core.models import ChatTurn, Photo


class ImageQuality(StrEnum):
    """Качество отрисовки.

    Пользователю не показывается и им не выбирается — это параметр тарифа
    в конфиге. Разница в цене между LOW и MEDIUM почти на порядок
    (docs/research.md §4.3), поэтому бесплатный тариф рисует в LOW.
    """

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ContentRefusedError(Exception):
    """Провайдер отказался работать с этим запросом по правилам содержания.

    Живёт в порту, а не в адаптере, потому что реагировать на такой отказ
    должно ядро: человеку надо сказать, что нарисовать это нельзя, а не
    «что-то пошло не так, попробуй ещё раз» — попыток тут сколько ни делай,
    ответ будет тот же.

    От сбоя провайдера отличается принципиально: повторять бессмысленно,
    предохранитель трогать нечестно (провайдер жив и ответил по существу), а
    лимит, как и при любой недоставке результата, не списывается.
    """


