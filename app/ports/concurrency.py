"""Порт ограничения одновременных задач.

Нужен маршрутизатору: между проверкой остатка и списанием есть окно, и два
параллельных запроса одного пользователя могли бы пройти проверку оба
(§3.4.8). Закрывается счётчиком одновременных задач на пользователя.

Протокол, а не прямой импорт FloodGuard из app/infra: ядро не должно зависеть
от инфраструктуры, даже когда та написана на чистом Python. Реализацию
подставляет app/main.py, а тесты подставляют свою — например, такую, которая
всегда отказывает.

Исключений в протоколе нет намеренно: ловить чужой класс ошибки значило бы
импортировать его. Два метода и try/finally у вызывающего дают то же самое.
"""

