"""Протоколы работы с файлами.

Два разных дела и потому два разных протокола: разобрать присланное и собрать
готовое. Их объединение выглядело бы симметрично, но у них нет ни общего
состояния, ни общей причины меняться.
"""

from __future__ import annotations

from typing import Protocol

from app.core.documents import DocumentFormat
from app.core.models import Document


class DocumentUnreadableError(Exception):
    """Файл не открылся или оказался не тем, чем назвался.

    Отдельное исключение, потому что виноват файл, а не мы: человеку надо
    сказать «этот файл не читается», а не «что-то пошло не так». Битый архив,
    защищённый паролем документ и pptx под именем docx — всё сюда.
    """


class DocumentEmptyError(Exception):
    """Файл открылся, но текста в нём нет.

    Обычный случай — PDF со сканами: внутри картинки страниц, текстового слоя
    нет вовсе. Отправлять провайдеру пустоту незачем: он вернёт сочинение на
    вольную тему, а человек заплатит за него лимитом.
    """


class DocumentReader(Protocol):
    """Достаёт текст из присланного файла."""

