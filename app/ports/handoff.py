"""Порт передачи: что нужно кнопке-связке, когда её нажмут.

Под готовой презентацией стоит «Сделать доклад по презентации», под готовым
докладом — «Сделать презентацию по докладу». Каждой кнопке нужно знать, по
чему делать: тему презентации, а для презентации по докладу — ещё и сам текст
доклада. В данные кнопки это не положишь (у Telegram там 64 байта), а текст
доклада по правилу проекта в базу не кладётся вовсе.

Поэтому кнопка несёт короткий жетон, а то, на что он указывает, лежит здесь —
в памяти процесса, ограниченное время. После перезапуска или по истечении
срока жетон ни на что не указывает, и кнопка отвечает честно: данных уже нет.

Жетон забирается одной операцией. Два нажатия разом, повторная доставка —
работу получает ровно одно; второе узнаёт, что жетон уже взят.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True, slots=True)
class Carried:
    """Что передаётся по кнопке.

    ``material`` — текст доклада для презентации по нему. Пусто — только
    тема: так делается доклад по презентации.
    """

    topic: str
    material: str = ""


class Handoff(Protocol):
    """Хранилище жетонов для кнопок-связок."""

    def put(self, carried: Carried) -> str:
        """Кладёт и возвращает жетон для данных кнопки."""
        ...

    def peek(self, token: str) -> Carried | None:
        """Смотрит, не забирая. None — жетона нет или он уже взят."""
        ...

    def take(self, token: str) -> Carried | None:
        """Забирает. Повторное ``take`` того же жетона даст None."""
        ...

    def was_taken(self, token: str) -> bool:
        """Брали ли этот жетон: отличает «уже сделано» от «устарело»."""
        ...

    def give_back(self, token: str, carried: Carried) -> None:
        """Возвращает взятое, когда работа не удалась.

        Без возврата упавшая сборка сожгла бы кнопку: человек нажал бы её
        снова и услышал «уже сделано», хотя не получил ничего.
        """
        ...
