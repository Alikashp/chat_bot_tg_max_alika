"""Порт наблюдаемости.

Ядру нужно сообщать наружу о сбоях провайдеров — молча проглоченная ошибка в
денежном пути недопустима. Но тащить structlog в core нельзя: это библиотека
ввода-вывода, и тест чистоты ядра на неё справедливо ругается.

Поэтому ядро знает только этот протокол. Реальный structlog-логгер ему
подсовывает app/main.py, а тесты — фейк, по которому удобно проверять, что о
сбое действительно сообщили.
"""

from __future__ import annotations

from typing import Protocol


class Logger(Protocol):
    """Минимум, который нужен ядру. Совместим со structlog.

    Значения полей ограничены простыми типами намеренно: в лог не должны
    попадать объекты, у которых при сериализации всплывёт содержимое
    сообщения пользователя или токен (§3.5).
    """

    def info(self, event: str, **fields: str | int | float | bool | None) -> None:
        """Штатное событие."""
        ...

    def warning(self, event: str, **fields: str | int | float | bool | None) -> None:
        """Что-то пошло не так, но обработано."""
        ...

    def error(self, event: str, **fields: str | int | float | bool | None) -> None:
        """Сбой, о котором нужно знать."""
        ...
