"""Порты оплаты.

Портов два, а не один, и это не усложнение ради стройности. Оплата картой и
оплата звёздами Telegram устроены принципиально по-разному:

* **Карта (ЮKassa).** Мы просим у провайдера платёж, получаем ссылку и
  показываем её кнопкой. Деньги приходят где-то снаружи, мессенджер про них
  не знает вовсе. Работает в обоих мессенджерах.
* **Звёзды.** Счёт выставляет сам Telegram, оплата проходит внутри него, и
  никакого внешнего провайдера нет. В MAX такого механизма не существует.

Свести их в один протокол можно было бы только фиктивной реализацией для MAX —
методом, который никогда не вызывается. Это ровно та заглушка, которую
запрещает §8 задания. Поэтому портов два, и каждый может отсутствовать:
``None`` означает «этим способом здесь не платят».
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Protocol

from app.core.models import Chat, MessageRef


class PaymentMethod(StrEnum):
    """Способ оплаты (§2.8)."""

    CARD = "card"
    STARS = "stars"


class PaymentStatus(StrEnum):
    """Что с платежом происходит."""

    #: Счёт выставлен, денег пока нет.
    PENDING = "pending"
    #: Деньги получены, тариф выдан.
    PAID = "paid"
    #: Платёж отменён или протух.
    CANCELED = "canceled"


@dataclass(frozen=True, slots=True)
class PaymentIntent:
    """Начатый платёж у провайдера.

    ``confirmation_url`` — куда отправить человека платить. Если его нет,
    значит провайдер уже показал счёт сам, и от нас больше ничего не нужно.
    """

    external_id: str
    confirmation_url: str | None = None


class CardPayments(Protocol):
    """Провайдер оплаты картой."""

    async def create_payment(
        self,
        *,
        order_id: str,
        amount_rub: int,
        description: str,
    ) -> PaymentIntent:
        """Начинает платёж и возвращает, куда отправить человека.

        ``order_id`` — наш идентификатор заказа. Он же служит ключом
        идемпотентности: повторное нажатие кнопки не должно создавать второй
        платёж, а провайдер обязан вернуть тот же самый.
        """
        ...

    async def is_paid(self, external_id: str, *, expected_rub: int) -> bool:
        """Спрашивает у провайдера, оплачен ли платёж на нужную сумму.

        Существует затем, что уведомлению о платеже верить нельзя: у ЮKassa
        вебхук не подписан ничем, кроме адреса отправителя. Уведомление —
        только повод спросить, а отвечает на вопрос сам провайдер, по нашему
        ключу. Без этого любой, кто узнал адрес вебхука, выдавал бы себе
        подписки.
        """
        ...


class StarsPayments(Protocol):
    """Оплата звёздами Telegram.

    Отдельный порт, потому что счёт выставляет сам мессенджер: внешнего
    провайдера, у которого можно было бы спросить статус, здесь нет.
    """

    async def send_invoice(
        self,
        chat: Chat,
        *,
        title: str,
        description: str,
        order_id: str,
        stars: int,
    ) -> MessageRef:
        """Выставляет счёт средствами мессенджера."""
        ...

    async def approve(
        self, request_id: str, *, ok: bool, reason: str | None = None
    ) -> None:
        """Подтверждает готовность принять оплату.

        Telegram спрашивает об этом перед списанием и ждёт ответа считаные
        секунды. Отказ здесь дешевле разбирательства с возвратом денег за
        заказ, которого у нас нет.
        """
        ...
