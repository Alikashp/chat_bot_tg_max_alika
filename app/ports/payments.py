"""Порты оплаты.

Портов два, а не один, и это не усложнение ради стройности. Оплата картой и
оплата звёздами Telegram устроены принципиально по-разному:

* **Карта (ЮKassa).** Мы просим у провайдера платёж, получаем ссылку и
  показываем её кнопкой. Деньги приходят где-то снаружи, мессенджер про них
  не знает вовсе. Работает в обоих мессенджерах.
* **Звёзды.** Счёт выставляет сам Telegram, оплата проходит внутри него, и
  никакого внешнего провайдера нет. В MAX такого механизма не существует.

Свести их в один протокол можно было бы только фиктивной реализацией для MAX —
методом, который никогда не вызывается. Это ровно та заглушка, которую
запрещает §8 задания. Поэтому портов два, и каждый может отсутствовать:
``None`` означает «этим способом здесь не платят».
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Protocol

from app.core.receipts import Receipt


class PaymentMethod(StrEnum):
    """Способ оплаты (§2.8)."""

    CARD = "card"
    STARS = "stars"


class PaymentStatus(StrEnum):
    """Что с платежом происходит."""

    #: Счёт выставлен, денег пока нет.
    PENDING = "pending"
    #: Деньги получены, тариф выдан.
    PAID = "paid"
    #: Платёж отменён или протух.
    CANCELED = "canceled"


class SubscriptionStatus(StrEnum):
    """Что с подпиской."""

    #: Списания идут по расписанию.
    ACTIVE = "active"
    #: Человек отменил продление. Оплаченный период дорабатывает.
    CANCELLED = "cancelled"
    #: Списание не прошло. Ещё пробуем, но недолго.
    PAST_DUE = "past_due"


@dataclass(frozen=True, slots=True)
class PaymentIntent:
    """Начатый платёж у провайдера.

    ``confirmation_url`` — куда отправить человека платить. Если его нет,
    значит провайдер уже показал счёт сам, и от нас больше ничего не нужно.
    """

    external_id: str
    confirmation_url: str | None = None


class CardPayments(Protocol):
    """Провайдер оплаты картой."""

    #: Умеет ли провайдер списывать повторно без участия человека.
    #: У ЮKassa это отдельно подключаемая возможность, и пока её не включили,
    #: подписка на карте невозможна — списание будет только первое.
    recurring: bool

    async def create_payment(
        self,
        *,
        order_id: str,
        amount_rub: int,
        description: str,
        save_method: bool = False,
        receipt: Receipt | None = None,
    ) -> PaymentIntent:
        """Начинает платёж и возвращает, куда отправить человека.

        ``order_id`` — наш идентификатор заказа. Он же служит ключом
        идемпотентности: повторное нажатие кнопки не должно создавать второй
        платёж, а провайдер обязан вернуть тот же самый.

        ``save_method`` просит провайдера запомнить способ оплаты, чтобы потом
        списывать без участия человека. Реквизиты карты при этом остаются у
        него: нам возвращается только идентификатор.

        ``receipt`` — данные для фискального чека (54-ФЗ). None означает, что
        чеки через провайдера не формируются: их может выставлять сам
        мессенджер или онлайн-касса без нашего участия.
        """
        ...

    async def charge_saved(
        self,
        *,
        order_id: str,
        amount_rub: int,
        description: str,
        payment_method_id: str,
        receipt: Receipt | None = None,
    ) -> str | None:
        """Списывает по ранее сохранённому способу оплаты.

        Возвращает идентификатор платежа у провайдера или None, если списание
        не прошло. Отказ — обычное дело: на карте не хватило денег, у неё
        истёк срок, банк не пропустил. Это не сбой сервиса, и обрабатывается
        он не исключением, а по §4.16 оферты: повторами в течение трёх дней и
        возвратом на бесплатные лимиты.

        Исключение остаётся за случаем, когда провайдер не ответил вовсе:
        тогда неизвестно, списали деньги или нет, и считать попытку неудачной
        нельзя — иначе сбой сети стоил бы человеку подписки.

        ``receipt`` нужен здесь ровно так же, как и при первой оплате: закон
        не делает скидки на то, что человека в этот момент нет за экраном.
        """
        ...

    async def saved_method_of(self, external_id: str) -> str | None:
        """Идентификатор способа оплаты, сохранённого при этом платеже.

        Возвращается провайдером только после успешной оплаты, поэтому
        спрашивается тогда же, когда и статус.
        """
        ...

    async def is_paid(self, external_id: str, *, expected_rub: int) -> bool:
        """Спрашивает у провайдера, оплачен ли платёж на нужную сумму.

        Существует затем, что уведомлению о платеже верить нельзя: у ЮKassa
        вебхук не подписан ничем, кроме адреса отправителя. Уведомление —
        только повод спросить, а отвечает на вопрос сам провайдер, по нашему
        ключу. Без этого любой, кто узнал адрес вебхука, выдавал бы себе
        подписки.
        """
        ...


class StarsPayments(Protocol):
    """Подписка на звёздах Telegram.

    Отдельный порт, потому что здесь всё иначе: счёт выставляет мессенджер,
    он же списывает каждый период сам, и внешнего провайдера, у которого
    можно спросить статус, не существует. Нам остаётся выставить счёт,
    услышать про оплату и уметь отменить.
    """

    async def subscription_link(
        self,
        *,
        title: str,
        description: str,
        order_id: str,
        stars: int,
        period_days: int,
    ) -> str:
        """Готовит счёт на подписку и возвращает ссылку на оплату.

        Именно ссылку, а не сообщение: счёт с подпиской Telegram умеет
        создавать только так. Кнопку с этой ссылкой рисует сценарий — он же
        рисует и всё остальное на экране оплаты.
        """
        ...

    async def cancel(self, *, user_id: str, charge_id: str) -> None:
        """Отменяет подписку на стороне мессенджера.

        Без этого вызова Telegram продолжит списывать звёзды, даже если у нас
        подписка отмечена отменённой, — и человек будет прав, требуя возврат.
        """
        ...

    async def approve(
        self, request_id: str, *, ok: bool, reason: str | None = None
    ) -> None:
        """Подтверждает готовность принять оплату.

        Telegram спрашивает об этом перед списанием и ждёт ответа считаные
        секунды. Отказ здесь дешевле разбирательства с возвратом денег за
        заказ, которого у нас нет.
        """
        ...
