"""Порт сборки презентаций.

Презентацию собирает внешний сервис (docs/API.md): колода создаётся, потом
собирается десятки секунд, потом отдаёт два файла. Ядру из этого видно одно
действие — «собери по теме в таком оформлении» — и список оформлений, из
которых человек выбирает. Опрос статуса, повторы и таймауты живут в адаптере:
правила для них написаны провайдером (раздел 8), а не продуктом.

Ошибки разделены по тому, что сказать человеку, а не по кодам HTTP. Ядру всё
равно, упала колода на сервере или не дождалась пяти минут: в обоих случаях
человек видит «не получилось» и кнопку «Повторить», а презентация не
списывается. Отдельно стоит только перегрузка — там честный ответ «много
запросов, попробуй позже».
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True, slots=True)
class PresentationTheme:
    """Оформление колоды: идентификатор для запроса и название для кнопки."""

    id: str
    name: str


@dataclass(frozen=True, slots=True)
class BuiltPresentation:
    """Готовая колода в байтах.

    PDF может не собраться, когда PPTX собрался (предупреждение PDF_FAILED у
    провайдера). PPTX при этом полноценный файл, и человек получает его —
    это доставка, а не сбой.
    """

    pptx: bytes
    pdf: bytes | None = None


class PresentationError(RuntimeError):
    """Собрать не вышло: провайдер отказал, упал или ответил непонятно.

    ``code`` — машинный код провайдера, если он его назвал. Текста ошибки
    здесь нет намеренно: человеку мы показываем свои тексты, а в лог и в
    учёт уходит только код.
    """

    def __init__(self, code: str = "") -> None:
        super().__init__(code or type(self).__name__)
        self.code = code


class PresentationTimeoutError(PresentationError):
    """Колода не готова за отведённое время (пять минут, docs/API.md §8)."""


class PresentationBusyError(PresentationError):
    """Сейчас собрать нельзя: заняты все слоты или исчерпан лимит ключа.

    ``reached_api`` отличает наш собственный отказ (до провайдера не
    обращались вовсе) от отказа провайдера с кодом 429. Первый в учёт
    обращений не попадает — обращения не было.
    """

    def __init__(self, code: str = "", *, reached_api: bool = False) -> None:
        super().__init__(code)
        self.reached_api = reached_api


class Presentations(Protocol):
    """Сборка презентаций по теме."""

    async def themes(self) -> tuple[PresentationTheme, ...]:
        """Оформления, из которых можно выбрать.

        Список берётся у провайдера, а не зашит у нас: он пополняется, и
        зашитый однажды предложил бы человеку тему, которой уже нет.
        """
        ...

    async def build(self, topic: str, *, theme_id: str) -> BuiltPresentation:
        """Собирает колоду и возвращает её файлы.

        Возвращается только готовая колода с уже скачанными файлами: файлы у
        провайдера живут недолго, и держать ссылку на них вместо байтов
        значило бы однажды отдать человеку протухшую ссылку.
        """
        ...
