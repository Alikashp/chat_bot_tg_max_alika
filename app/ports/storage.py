    async def complete_payment(
        self,
        payment_id: str,
        *,
        tariff: TariffId,
        expires_at: datetime,
        seen_tariff: TariffId,
        seen_expiry: datetime | None,
        subscription: Subscription | None,
        norm_since: datetime,
        trial: bool = False,
    ) -> GrantOutcome:
        """Выдаёт оплаченное одной транзакцией: всё или ничего (П4).

        Заказ переходит pending → paid, человеку пишется тариф и срок, а
        подписка заводится или переносится. Сбой на любом из шагов не
        оставляет заказа paid без тарифа или без перенесённой подписки: тогда
        не меняется ничего, и подтверждение можно повторить.

        ``seen_tariff`` и ``seen_expiry`` — что вызывающий видел, считая
        новый срок. Если с тех пор их поменяли (второй заказ того же
        человека подтвердился раньше), ответ STALE: срок, посчитанный от
        старой даты, потерял бы оплаченный месяц.

        ``trial`` — заказ на пробный период. Тогда выдача идёт, только если
        у человека ещё не было ни пробного периода, ни другой оплаты, и
        отмечает заказ как давший пробный период. Иначе заказ всё равно
        становится paid, но ничего не выдаётся: TRIAL_USED. Два
        одновременных подтверждения разводит условие на тариф и срок:
        второе получит STALE, а на повторе — TRIAL_USED.

        ``norm_since`` — с какого момента считается месячная норма. Пишется
        той же транзакцией: оплата и обновление нормы — одно событие, и
        оплаченное без новой нормы было бы оплаченным наполовину.

        Обращений к провайдеру внутри нет и быть не должно: транзакция не
        ждёт чужую сеть.
        """
        ...

