"""Порт хранилища.

Хранилище отвечает за долговечность и атомарность, но не за продуктовые
правила. Решение «списывать из дневной квоты или из бонуса» принимает
core/limits.py, а хранилище лишь выполняет атомарные примитивы. Иначе эта
логика продублировалась бы в каждой реализации порта.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Protocol

from app.core.models import (
    NO_USERNAME,
    DialogState,
    MessengerKind,
    Payment,
    Subscription,
    TariffId,
    Usage,
    User,
    UserId,
)


class Storage(Protocol):
    """Долговременное хранилище пользователей, расхода, диалогов и рефералов."""

    # --- Пользователи --------------------------------------------------

    async def get_user(self, messenger: MessengerKind, external_id: str) -> User | None:
        """Находит пользователя по идентификатору в мессенджере."""
        ...

    async def get_user_by_id(self, user_id: UserId) -> User | None:
        """Находит пользователя по внутреннему идентификатору."""
        ...

    async def set_username(self, user_id: UserId, username: str) -> None:
        """Запоминает имя пользователя в мессенджере.

        Вызывается при каждом обращении, а не только при регистрации: имя
        меняют когда захотят, и через месяц записанное однажды будет
        указывать не на того человека. Протухшее имя хуже, чем никакого —
        по нему поддержка пойдёт искать и найдёт постороннего.
        """
        ...

    async def get_user_by_referral_code(self, code: str) -> User | None:
        """Находит пользователя по его реферальному коду."""
        ...

    async def create_user(
        self,
        *,
        messenger: MessengerKind,
        external_id: str,
        referral_code: str,
        support_number: int,
        daily_image_quota: int,
        username: str = NO_USERNAME,
    ) -> User:
        """Заводит нового пользователя — или возвращает уже заведённого.

        Повторный вызов с той же парой (messenger, external_id) не ошибка, а
        обычное дело: два первых обновления от нового человека приходят почти
        одновременно и обрабатываются параллельно, поэтому оба видят «его ещё
        нет» и оба пытаются его завести. Побеждает один, второй получает того
        же пользователя. Иначе человек вместо ответа видит ошибку на первом
        же касании.

        Занятый ``referral_code`` или ``support_number`` — другое дело: это
        случайные величины, и коллизия означает «возьми другую». На неё
        реализация обязана бросить ValueError.
        """
        ...

    async def set_tariff(
        self,
        user_id: UserId,
        tariff: TariffId,
        expires_at: datetime | None,
    ) -> None:
        """Меняет тариф пользователя."""
        ...

    async def set_pending(self, user_id: UserId, pending: str | None) -> None:
        """Запоминает, чего бот ждёт от пользователя следующим сообщением.

        None сбрасывает ожидание. Хранится в базе, а не в памяти процесса:
        выкатка посреди разговора не должна превращать «Опиши, что нарисовать»
        в потерянный вопрос.
        """
        ...

    async def set_retry_context(self, user_id: UserId, context: str | None) -> None:
        """Запоминает, что повторить по кнопке «Ещё раз».

        Контекст один на пользователя и перезаписывается: «ещё раз»
        осмысленно относится к последнему результату.
        """
        ...

    # --- Расход --------------------------------------------------------

    async def get_usage(self, user_id: UserId, day: date) -> Usage:
        """Возвращает расход за указанные сутки.

        Для суток, за которые ещё ничего не потрачено, возвращает нулевой
        Usage, а не None: «не тратил» и «нет записи» — это одно и то же.
        """
        ...

    async def add_usage(
        self,
        user_id: UserId,
        day: date,
        *,
        messages: int = 0,
        images: int = 0,
    ) -> Usage:
        """Атомарно увеличивает дневной расход и возвращает новое значение."""
        ...

    async def spend_bonus(
        self,
        user_id: UserId,
        *,
        messages: int = 0,
        images: int = 0,
    ) -> bool:
        """Атомарно списывает бонусный баланс.

        Возвращает False и ничего не меняет, если баланса не хватает. Это
        всё-или-ничего: частичного списания быть не должно.
        """
        ...

    async def add_bonus(
        self,
        user_id: UserId,
        *,
        messages: int = 0,
        images: int = 0,
    ) -> None:
        """Атомарно начисляет бонусный баланс (награда за реферала)."""
        ...

    # --- Оплата --------------------------------------------------------

    async def create_payment(
        self,
        *,
        user_id: UserId,
        tariff: TariffId,
        method: str,
        amount: int,
        currency: str,
        docs_version: str,
    ) -> Payment:
        """Заводит заказ на подписку до обращения к провайдеру.

        ``docs_version`` — редакция оферты и политики, которую человек принял,
        нажав кнопку оплаты. Хранится вместе с заказом: документы меняются, а
        доказательством согласия остаётся то, что действовало в тот момент.

        Своя запись нужна затем, чтобы уведомление об оплате было с чем
        сверить: без неё мы верили бы на слово тому, кто постучался на вебхук.
        """
        ...

    async def get_payment(self, payment_id: str) -> Payment | None:
        """Находит заказ по нашему идентификатору."""
        ...

    async def attach_external_id(self, payment_id: str, external_id: str) -> bool:
        """Запоминает идентификатор платежа у провайдера.

        Возвращает False, если этот платёж уже привязан к другому заказу.
        Такого быть не должно — ключом идемпотентности служит наш заказ, — но
        если случилось, отдавать ссылку нельзя: подтвердить оплату по ней мы
        всё равно не сможем, а деньги человек отдаст.
        """
        ...

    async def mark_paid(self, payment_id: str) -> bool:
        """Атомарно переводит заказ в «оплачен».

        Возвращает True только при первом переходе. Это и есть защита от
        двойной выдачи: уведомление об оплате приходит по несколько раз, и
        продлевать подписку на каждое нельзя.
        """
        ...

    # --- Подписка ------------------------------------------------------

    async def get_subscription(self, user_id: UserId) -> Subscription | None:
        """Действующая подписка пользователя; None — если её нет."""
        ...

    async def save_subscription(self, subscription: Subscription) -> None:
        """Заводит подписку или заменяет существующую.

        Заменяет, а не добавляет: подписка у человека одна, смена тарифа —
        это та же подписка с другим тарифом. Две строки означали бы два
        списания в месяц.
        """
        ...

    async def advance_subscription(
        self,
        user_id: UserId,
        *,
        next_charge_at: datetime,
        status: str,
        failed_since: datetime | None,
        amount: int | None = None,
    ) -> bool:
        """Двигает подписку к следующей попытке. False — трогать было нечего.

        Существует затем, что фоновый проход работает с копией, прочитанной в
        его начале, а между чтением и записью человек успевает нажать
        «Отключить продление»: проход идёт с обращениями к провайдеру и
        мессенджеру, и длится это секунды. Записать копию целиком значило бы
        воскресить отменённую подписку и списать в следующем месяце деньги,
        от которых человек отказался.

        Поэтому обновление точечное и условное: отменённую подписку оно не
        трогает вовсе и возвращает False. ``amount`` со значением None не
        меняет сумму.
        """
        ...

    async def cancel_subscription(self, user_id: UserId, at: datetime) -> bool:
        """Прекращает будущие списания. False — если отменять было нечего.

        Оплаченный период при этом не трогается: он дорабатывает до конца
        (§4.15 оферты).
        """
        ...

    async def subscriptions_to_charge(
        self, now: datetime, *, limit: int
    ) -> list[Subscription]:
        """Подписки, по которым пора списывать."""
        ...

    async def subscriptions_to_remind(
        self, since: datetime, until: datetime, *, limit: int
    ) -> list[Subscription]:
        """Подписки, о списании по которым пора предупредить (§4.13).

        Окно ограничено с обеих сторон. Сверху — сутками: раньше предупреждать
        рано. Снизу — текущим моментом: у просроченного списания «завтра» уже
        прошло, и слать про него предупреждение значило бы соврать в дате.
        Просроченными занимается проход списаний.

        Возвращает только те, о которых ещё не предупреждали: повторное
        напоминание раздражает не меньше, чем его отсутствие.
        """
        ...

    async def mark_reminded(self, user_id: UserId, charge_at: datetime) -> None:
        """Отмечает, что о списании такого-то числа человек предупреждён."""
        ...

    async def subscriptions_to_check_price(
        self, since: datetime, until: datetime, *, limit: int
    ) -> list[Subscription]:
        """Подписки, у которых пора сверить цену с тарифом (§4.17).

        Сверка нужна за неделю до списания: если цена тарифа изменилась,
        предупредить надо заранее, а не поставить перед фактом. Нижняя
        граница по той же причине, что и у напоминания: просроченному
        списанию новую цену объявлять поздно — семи дней у него уже нет.
        """
        ...

    async def mark_price_checked(self, user_id: UserId, charge_at: datetime) -> None:
        """Отмечает, что цена к такому-то списанию сверена.

        Отметка ставится и тогда, когда цена не менялась и говорить было
        нечего: иначе сверка повторялась бы каждый тик планировщика всю
        неделю до списания.
        """
        ...

    # --- Диалог --------------------------------------------------------

    async def get_dialog(self, user_id: UserId) -> DialogState:
        """Возвращает состояние диалога; для нового пользователя — пустое."""
        ...

    async def save_dialog(self, user_id: UserId, dialog: DialogState) -> None:
        """Сохраняет состояние диалога."""
        ...

    async def reset_dialog(self, user_id: UserId) -> None:
        """Начинает диалог заново («🔄 Новый диалог»)."""
        ...

    # --- Рефералы ------------------------------------------------------

    async def record_referral(self, referrer_id: UserId, referee_id: UserId) -> bool:
        """Фиксирует реферальную связь.

        Возвращает True, если связь записана впервые, и False, если такая
        пара уже была. Идемпотентность обязана обеспечиваться самим
        хранилищем (в PostgreSQL — ограничением уникальности), а не
        проверкой в вызывающем коде: только так повторный /start физически
        не сможет начислить награду дважды.

        Реализация обязана отвергать self-referral (referrer_id == referee_id),
        возвращая False.
        """
        ...

    async def count_referrals(self, referrer_id: UserId) -> int:
        """Сколько всего друзей привёл пользователь (для профиля)."""
        ...

    async def count_referrals_since(self, referrer_id: UserId, since: datetime) -> int:
        """Сколько наград начислено с указанного момента (суточный антифрод)."""
        ...
