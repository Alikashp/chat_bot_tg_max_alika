"""Реестр того, что бот умеет делать с присланным файлом.

Устроен как реестр приколов и ровно по той же причине: новое действие — это
запись здесь и больше ничего. Ни обработчика, ни ветки в маршрутизаторе, ни
строчки в настройках.

Инструкция провайдеру живёт рядом с подписью кнопки намеренно. Разойтись им
нельзя: человек нажал «Реферат» и обязан получить реферат, а не доклад.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from types import MappingProxyType


@dataclass(frozen=True, slots=True)
class DocumentAction:
    """Одно действие над присланным файлом."""

    #: Устойчивый идентификатор. Попадает в данные кнопок, поэтому менять его
    #: у выпущенного действия нельзя: у людей в переписке останутся старые
    #: кнопки, и они перестанут работать.
    id: str

    #: Подпись кнопки в меню.
    button: str

    #: Чем просим прислать файл. Своё у каждого действия: «кинь методичку» и
    #: «кинь статью» — разные просьбы, и общая формулировка обеим врёт.
    invitation: str

    #: Заголовок готового файла. Он же становится именем файла, который
    #: человек увидит у себя в загрузках.
    title: str

    #: Инструкция провайдеру. Пользователю не показывается.
    instruction: str


#: Реестр действий. Порядок записей — порядок кнопок в меню.
DOCUMENT_ACTIONS: Mapping[str, DocumentAction] = MappingProxyType(
    {
        "report": DocumentAction(
            id="report",
            button="📊 Доклад",
            invitation="Кинь файл — сделаю по нему доклад",
            title="Доклад",
            # Про «только по тексту файла» сказано не для красоты. Модель
            # охотно дополняет доклад тем, что знает про тему вообще, и
            # человек получает чужие цифры под своим заголовком.
            instruction=(
                "Ты готовишь доклад по присланному документу. Пиши по-русски.\n"
                "Опирайся только на текст документа: ничего не додумывай и не "
                "добавляй сведения со стороны. Чего в документе нет — того нет "
                "и в докладе.\n"
                "Структура: короткое вступление, затем разделы по смыслу, затем "
                "выводы. Каждый раздел начинай строкой вида «## Название».\n"
                "Сохраняй все числа, даты и имена ровно так, как они стоят в "
                "документе.\n"
                "Не пиши вступительных фраз вроде «конечно» и не описывай, что "
                "ты сейчас сделаешь: сразу текст доклада."
            ),
        ),
        "abstract": DocumentAction(
            id="abstract",
            button="📝 Реферат",
            invitation="Кинь файл — сделаю по нему реферат",
            title="Реферат",
            instruction=(
                "Ты готовишь реферат по присланному документу. Пиши по-русски.\n"
                "Реферат — это краткое изложение своими словами, а не пересказ "
                "подряд и не набор цитат. Объём — примерно десятая часть "
                "исходного текста.\n"
                "Опирайся только на текст документа: ничего не додумывай.\n"
                "Начни с темы и главной мысли, дальше — основное содержание "
                "разделами вида «## Название», в конце — короткий вывод.\n"
                "Не пиши вступительных фраз: сразу текст реферата."
            ),
        ),
        "notes": DocumentAction(
            id="notes",
            button="📌 Конспект",
            invitation="Кинь файл — сделаю по нему конспект",
            title="Конспект",
            instruction=(
                "Ты готовишь конспект присланного документа. Пиши по-русски.\n"
                "Конспект — это тезисы, а не связный текст: короткие пункты, "
                "по одному на мысль, строками вида «- пункт».\n"
                "Группируй пункты по темам, каждую тему начинай строкой вида "
                "«## Название».\n"
                "Обязательно выноси все числа, даты, определения и формулы — "
                "ради них конспект и делают.\n"
                "Опирайся только на текст документа. Не пиши вступительных "
                "фраз: сразу конспект."
            ),
        ),
    }
)


def action_of(action_id: str) -> DocumentAction | None:
    """Действие по идентификатору; None — такого нет."""
    return DOCUMENT_ACTIONS.get(action_id)
