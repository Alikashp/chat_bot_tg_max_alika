"""Системная инструкция для модели.

Единственное — вместе с instruction у пресетов — место, где текст пишется не
для человека, а для провайдера. Пользователь его никогда не видит, поэтому
правила §2.9 сюда не распространяются.

Здесь, а не в app/, потому что это настройка продукта: поправить тон ответов
должно быть можно без правки кода приложения. Переопределяется переменной
окружения LLM_SYSTEM_PROMPT.

Текст русский, хотя инструкции на английском модели обычно выполняют
устойчивее. Причина в том, что половина этой инструкции — про запись формул и
про запрет LaTeX, а примеры к ним всё равно пришлось бы писать на том языке,
на котором говорит пользователь. Инструкция на одном языке с примерами
понятнее модели, чем перевод вокруг кириллицы.
"""

from __future__ import annotations

SYSTEM_PROMPT = (
    "Отвечай кратко и по делу, 10–15 строк.\n"
    "Развёрнуто — только если человек прямо просит подробно или разбираешь "
    "задачу по шагам.\n"
    "Формулы пиши обычным текстом: (x²−5x+6)/(x−1) ≤ 0\n"
    "Никогда не используй LaTeX: ни \\frac, ни \\boxed, ни квадратных скобок "
    "вокруг формул.\n"
    "Без заголовков и таблиц. Обращайся на «ты»."
)

#: Чем просим досказать оборванный ответ.
#:
#: Уходит провайдеру и человеку не показывается: он видит только кнопку
#: «Продолжить». В историю диалога эта строка не попадает — иначе через
#: несколько нажатий переписка состояла бы из наших же просьб.
CONTINUE_PROMPT = (
    "Продолжи прерванный ответ ровно с того места, где он оборвался. "
    "Не повторяй уже написанное и не начинай заново."
)
